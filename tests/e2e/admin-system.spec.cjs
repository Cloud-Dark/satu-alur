// E2E: admin by email (VITE_ADMIN_EMAILS = boss@contoh.id in run.cjs, the mock's ADMIN_EMAILS),
// Kantor › Sistem pages, the user detail dialog, and Pengaturan › Email & AI for a business.
const { loginLive } = require('./lib.cjs')

module.exports = async function adminSystem(t) {
  // Login page: Google button stays hidden when Google is not configured (mock).
  const l = await t.page()
  await l.goto(`${t.base}/#/masuk`, { waitUntil: 'load' })
  await l.waitForSelector('#auth-email')
  await l.waitForTimeout(400)
  t.check(await l.locator('.auth-google-box').isHidden(), 'login: "Masuk dengan Google" hidden when not configured')
  await l.goto(`${t.base}/#/masuk?google_error=${encodeURIComponent('Masuk dengan Google dibatalkan.')}`)
  await l.reload()
  await l.waitForSelector('#auth-email')
  t.check(await l.getByText('Masuk dengan Google dibatalkan.').count() === 1, 'login: Google error from the callback is shown')
  await l.close()

  // Email admin: business app first, with a switch to Kantor Satu Alur.
  const p = await t.page()
  await loginLive(p, t.base, 'boss@contoh.id')
  const sw = p.locator('.side-row-office')
  t.check(await sw.count() === 1 && /Kantor Satu Alur/.test(await sw.textContent()), 'email admin: "Kantor Satu Alur" switch in the sidebar')
  t.check(await p.locator('.flow-item[data-stage="dashboard"]').count() === 1, 'email admin: starts in the business app')
  await sw.click()
  await p.waitForSelector('.flow-item[data-stage="sys-overview"]', { timeout: 8000 })
  const groups = await p.locator('.side-label > span:first-child').allTextContents()
  t.check(groups.at(-1) === 'Sistem' && groups.includes('Bisnis') && groups.includes('Pelanggan'), 'Kantor: office groups plus Sistem', groups.join('|'))
  await p.click('.flow-item[data-stage="sys-overview"]')
  await p.getByText('Kesehatan sistem').waitFor({ timeout: 8000 })
  t.check(await p.locator('.kpi').count() >= 5, 'Sistem › Ringkasan: KPI cards')
  t.check(await p.locator('.side-row-office').textContent().then((x) => /Kembali ke usaha/.test(x)), 'Kantor: switch back to the business app offered')

  // Email settings: toggle and save, then simulated test send.
  await p.click('.flow-item[data-stage="sys-email"]')
  await p.getByText('Pengiriman email').first().waitFor({ timeout: 8000 })
  await p.getByText('Izinkan bisnis memakai SMTP sendiri').click()
  await p.getByRole('button', { name: 'Simpan' }).click()
  await p.getByText('Pengaturan disimpan.').first().waitFor({ timeout: 5000 }).catch(() => {})
  const saved = await p.evaluate(() => JSON.parse(localStorage.getItem('satualur_system_demo_v1') || '{}'))
  t.check(saved.settings?.email?.allow_custom_smtp === false, 'Sistem › Email: setting saved', JSON.stringify(saved.settings))
  await p.getByRole('button', { name: 'Kirim email uji' }).click()
  await p.getByText(/Simulasi: email uji dicatat/).waitFor({ timeout: 5000 }).catch(() => {})
  t.check(await p.getByText(/Simulasi: email uji dicatat/).count() === 1, 'Sistem › Email: test email simulated in demo mode')

  // Log aktivitas shows the simulated email; AI + Login + WhatsApp pages render.
  await p.click('.flow-item[data-stage="sys-activity"]')
  await p.getByText('Email terkirim').waitFor({ timeout: 8000 })
  t.check(await p.locator('.data-table td', { hasText: 'Uji admin' }).count() >= 1, 'Log aktivitas: admin test email listed')
  await p.click('.flow-item[data-stage="sys-ai"]')
  await p.getByRole('button', { name: 'Uji mesin AI' }).click()
  await p.getByText(/menjawab/).waitFor({ timeout: 5000 }).catch(() => {})
  t.check(await p.getByText(/menjawab/).count() === 1, 'Sistem › Mesin AI: test reply shown')
  await p.click('.flow-item[data-stage="sys-login"]')
  await p.getByText('Redirect URI Google').waitFor({ timeout: 5000 })
  t.check(/\/api\/auth\/google\/callback$/.test(await p.locator('.of-sys-code').textContent()), 'Sistem › Login: Google redirect URI shown')
  await p.click('.flow-item[data-stage="sys-whatsapp"]')
  await p.getByText('Cadangan pengirim platform').waitFor({ timeout: 5000 })
  t.check(await p.getByText('Mati (default)').count() === 1, 'Sistem › WhatsApp: platform fallback off by default')

  // Pengguna: list + detail dialog with skala akun.
  await p.click('.flow-item[data-stage="users"]')
  await p.locator('.of-user').first().waitFor({ timeout: 8000 })
  await p.locator('.of-user', { hasText: 'boss@contoh.id' }).getByRole('button', { name: 'Detail' }).click()
  await p.waitForSelector('dialog.modal[open]')
  t.check(await p.locator('dialog.modal[open]').getByText('Skala akun').count() >= 1, 'Pengguna › Detail: dialog with skala akun')
  await p.selectOption('dialog.modal[open] select', 'enterprise').catch(() => {})
  await p.locator('dialog.modal[open]').getByRole('button', { name: 'Simpan skala' }).click()
  await p.getByText('Skala akun disimpan.').first().waitFor({ timeout: 5000 }).catch(() => {})
  t.check(await p.getByText('Skala akun disimpan.').count() >= 1, 'Pengguna › Detail: skala akun saved')

  // Back to the business app: Pengaturan › Email & AI.
  await p.click('.side-row-office')
  await p.waitForSelector('.flow-item[data-stage="dashboard"]', { timeout: 8000 })
  await p.getByRole('button', { name: 'Pengaturan' }).first().click()
  await p.waitForSelector('.drawer.is-open')
  await p.click('.drawer .seg-btn[data-value="integrations"]')
  await p.getByText('Pengiriman email').waitFor({ timeout: 5000 })
  await p.getByText('OpenAI-compatible').click()
  await p.fill('.drawer input[id^="set-ai-base-"]', 'https://api.openai.com/v1')
  await p.fill('.drawer input[id^="set-ai-model-"]', 'gpt-4o-mini')
  await p.fill('.drawer input[id^="set-ai-key-"]', 'sk-test-123')
  await p.getByRole('button', { name: 'Simpan mesin AI' }).click()
  await p.getByText('Mesin AI disimpan.').first().waitFor({ timeout: 5000 }).catch(() => {})
  await p.waitForSelector('.drawer input[id^="set-ai-key-"]')
  t.check(/Tersimpan/.test(await p.getAttribute('.drawer input[id^="set-ai-key-"]', 'placeholder') || '') && await p.inputValue('.drawer input[id^="set-ai-key-"]') === '', 'Email & AI: key saved, never shown again')
  await p.getByRole('button', { name: 'Kirim email uji' }).click()
  await p.getByText(/Simulasi: di akun demo|Email uji terkirim/).waitFor({ timeout: 5000 }).catch(() => {})
  t.check(await p.getByText(/Simulasi: di akun demo|Email uji terkirim/).count() === 1, 'Email & AI: test email (simulated in mock)')
  await t.noErrors?.(p)
  await p.close()
}
