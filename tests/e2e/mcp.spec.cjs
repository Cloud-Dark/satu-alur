// Exercise the connector form and migration wizard through real controls in mock mode.
const { loginLive } = require('./lib.cjs')
module.exports = async function mcp(t) {
  const p = await t.page()
  await loginLive(p, t.base)
  await p.click('.side-row')
  await p.click('.drawer .seg-btn[data-value="erp"]')
  await p.getByRole('button', { name: 'CSV / JSON', exact: false }).click()
  await p.fill('#mcp-name', 'CSV integration')
  await p.check('.drawer .checkbox-label input')
  await p.getByRole('button', { name: 'Simpan konektor', exact: true }).click()
  await p.waitForSelector('.mcp-card')
  const conn = await p.evaluate(() => JSON.parse(localStorage.getItem('satualur_mcp_connectors'))[0])
  t.check(conn.type === 'file' && conn.enabled && conn.config.format === 'csv', 'file connector preserves form type, enabled and format')
  await p.getByRole('button', { name: 'Peta', exact: true }).click()
  const csv = 'name,phone\nWorker example,08123456789\n'
  await p.locator('.mcp-file-input').setInputFiles({ name: 'workers.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  const trigger = p.locator('.combo:has(#mcp-entity) .combo-trigger')
  await trigger.click()
  await p.getByRole('option', { name: 'Tenaga Kerja', exact: true }).click()
  await p.waitForSelector('#map-src-name')
  t.check(await p.locator('#mcp-entity').inputValue() === 'workers', 'mapping select changes the actual entity')
  await p.getByRole('button', { name: 'Simpan pemetaan', exact: true }).click()
  await p.waitForFunction((id) => JSON.parse(localStorage.getItem('satualur_mcp_mappings') || '{}')[id]?.[0]?.entity === 'workers', conn.id)
  await p.click('.drawer .seg-btn[data-value="migration"]')
  await p.getByRole('button', { name: 'Migrasi baru', exact: true }).click()
  await p.fill('#mig-name', 'Workers migration')
  await p.getByRole('button', { name: 'Selanjutnya', exact: true }).click()
  t.check(await p.getByRole('button', { name: 'Sebelumnya', exact: true }).isVisible(), 'wizard step two adds the back button')
  await p.getByRole('button', { name: 'Selanjutnya', exact: true }).click()
  t.check(await p.getByRole('button', { name: 'Buat migrasi', exact: true }).isVisible(), 'wizard advances to a working creation action')
  await p.getByRole('button', { name: 'Buat migrasi', exact: true }).click()
  await p.waitForSelector('.mcp-run-progress')
  const before = await p.evaluate(() => localStorage.getItem('satualur_mcp_migrations'))
  await p.getByLabel('File workers', { exact: true }).setInputFiles({ name: 'workers.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await p.getByRole('button', { name: 'Periksa tanpa menyimpan', exact: true }).click()
  await p.waitForFunction(() => document.querySelector('.drawer [role="status"]')?.textContent.includes('Pratinjau: 1 diproses'))
  t.check(await p.evaluate(() => localStorage.getItem('satualur_mcp_migrations')) === before, 'dry run does not persist mock migration progress')
  await p.getByRole('button', { name: 'Jalankan fase 1', exact: true }).click()
  await p.waitForFunction(() => JSON.parse(localStorage.getItem('satualur_mcp_migrations'))[0].phases[0].status === 'completed')
  t.check(await p.getByRole('button', { name: 'Jalankan fase 2', exact: true }).isVisible(), 'running the phase advances to the next phase')
  await t.noErrors(p)
}
