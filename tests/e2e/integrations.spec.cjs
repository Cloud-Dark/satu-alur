// E2E: the business's own integrations on the mock cloud — WhatsApp (keys in Pengaturan, "Kirim via WhatsApp" from
// Permintaan with the confirm dialog, provider choice) and Repliz (keys in Media Sosial › Akun, connect an account,
// post from Jadwal, status in Laporan tayang). Everything is simulated in demo mode; no key reaches the browser storage.
const { loginLive, goStage, goHash } = require('./lib.cjs')

module.exports = async function integrations(t) {
  const p = await t.page()
  await loginLive(p, t.base)

  /* ---------------------------------------------------------------- WhatsApp */
  // The job detail in Alur kerja (#/app/alur-kerja/<id>) offers a WhatsApp follow-up.
  const withPhone = await p.evaluate(() => (JSON.parse(localStorage.getItem('satualur_mock_v1') || '{}').requests || []).find((r) => r.phone)?.id)
  const openJob = async () => {
    await goHash(p, `#/app/alur-kerja/${withPhone}`)
    await p.waitForSelector('dialog.wf-detail[open]', { timeout: 10000 })
  }
  t.check(await goStage(p, 'workflow'), 'sidebar has "Alur kerja"')
  await openJob()
  const waBtn = p.getByRole('button', { name: /via WhatsApp$/ }).first()
  t.check(await waBtn.count() === 1, 'job detail offers "WhatsApp" for a customer with a phone')
  await waBtn.click()
  await p.waitForSelector('dialog.modal[open]')
  await p.locator('dialog.modal .note', { hasText: 'Hubungkan akun WAPilot' }).waitFor({ timeout: 6000 }).catch(() => {})
  t.check(await p.locator('dialog.modal .note', { hasText: 'Hubungkan akun WAPilot atau WAConsole' }).count() === 1, 'not connected: dialog points to Pengaturan')
  t.check(await p.getByRole('button', { name: 'Kirim WhatsApp' }).isDisabled(), 'not connected: send disabled')
  await p.getByRole('button', { name: 'Buka Pengaturan' }).click()
  await p.waitForSelector('#ig-waconsole-app_key', { timeout: 8000 })
  await p.fill('#ig-waconsole-app_key', 'app12345')
  await p.fill('#ig-waconsole-auth_key', 'auth9876')
  await p.getByRole('button', { name: 'Hubungkan WAConsole' }).click()
  await p.locator('.ig-card[data-provider="waconsole"]', { hasText: 'Terhubung • …9876' }).waitFor({ timeout: 8000 }).catch(() => {})
  t.check(await p.locator('.ig-card[data-provider="waconsole"]', { hasText: 'Terhubung • …9876' }).count() === 1, 'WAConsole connected, shown as …9876')
  t.check(await p.locator('.ig-card[data-provider="waconsole"]', { hasText: 'belum bisa diperiksa' }).count() === 1, 'without a device id the keys are stored unverified')
  await p.fill('#ig-wapilot-token', 'aica_0123456789abcdef')
  await p.getByRole('button', { name: 'Hubungkan WAPilot' }).click()
  await p.waitForSelector('#wa-provider', { state: 'attached', timeout: 8000 }).catch(() => {})
  t.check(await p.locator('#wa-provider').count() === 1, 'two providers connected: "Kirim lewat" choice shown')
  await p.selectOption('#wa-provider', 'waconsole')
  await p.waitForTimeout(400)
  t.check(await p.locator('.set-section', { hasText: 'Dikirim lewat' }).locator('dd', { hasText: 'WAConsole' }).count() >= 1, 'provider choice saved')
  await p.fill('#wa-test-phone', '0813 1111 2222')
  await p.getByRole('button', { name: 'Kirim pesan uji' }).click()
  await p.locator('.set-section p[role=status]', { hasText: 'disimulasikan' }).waitFor({ timeout: 6000 }).catch(() => {})
  t.check(await p.locator('.set-section p[role=status]', { hasText: 'Pesan uji disimulasikan ke 62813' }).count() === 1, 'test message (simulated) to a typed number')
  t.check(!(await p.evaluate(() => JSON.stringify(localStorage))).includes('auth9876'), 'keys are not kept in the browser')
  t.check(!/(^|\s)null(\s|$)/.test(await p.locator('.drawer').innerText()), 'no stray "null" text in the connector cards')
  await p.keyboard.press('Escape')
  await p.waitForTimeout(400)

  await openJob()
  await p.getByRole('button', { name: /via WhatsApp$/ }).first().click()
  await p.waitForSelector('dialog.modal[open]')
  await p.locator('dialog.modal .note', { hasText: 'Dikirim lewat WAConsole' }).waitFor({ timeout: 6000 }).catch(() => {})
  t.check(await p.locator('dialog.modal .note', { hasText: 'Dikirim lewat WAConsole' }).count() === 1, 'dialog names the chosen provider')
  const preset = await p.inputValue('dialog.modal textarea')
  t.check(/Terima kasih sudah menghubungi/.test(preset), 'follow-up text prefilled and editable', preset.slice(0, 60))
  await p.fill('dialog.modal textarea', 'Halo, jadwal survei besok jam 10.')
  await p.getByRole('button', { name: 'Kirim WhatsApp' }).click()
  await p.waitForSelector('dialog.modal[open]', { state: 'detached', timeout: 6000 }).catch(() => {})
  const sent = await p.evaluate(() => JSON.parse(localStorage.getItem('satualur_wa_demo_v1') || '{}').sent || [])
  t.check(sent.length === 2 && sent[1].provider === 'waconsole' && sent[1].kind === 'followup', 'message sent (simulated) through WAConsole', JSON.stringify(sent))

  /* ---------------------------------------------------------------- Repliz */
  t.check(await goStage(p, 'social-media'), 'sidebar has "Media Sosial"')
  await p.waitForSelector('#ig-repliz-access_key', { timeout: 10000 })
  t.check(await p.locator('.panel', { hasText: 'Hubungkan akun Repliz Anda' }).count() === 1, 'no Repliz keys yet: keys form in Akun')
  t.check(await p.locator('.panel', { hasText: 'Hubungkan akun Repliz Anda' }).locator('a[href*="repliz.com"]').count() === 1, 'link to where the keys are')
  await p.fill('#ig-repliz-access_key', '1234567890')
  await p.fill('#ig-repliz-secret_key', 'secret-abcdef-123')
  await p.getByRole('button', { name: 'Hubungkan Repliz' }).click()
  await p.waitForSelector('.rz-grid', { timeout: 8000 })
  t.check(await p.locator('.rz-card').count() === 8, 'eight platform cards after the keys are saved')
  await p.getByRole('button', { name: 'Hubungkan akun Instagram' }).click()
  await p.locator('.rz-card', { hasText: '1 akun terhubung' }).waitFor({ timeout: 6000 }).catch(() => {})
  t.check(await p.locator('.rz-card', { hasText: '@demo.instagram' }).count() === 1, 'Instagram connected (simulated)')
  await p.getByRole('button', { name: 'Hubungkan akun Threads' }).click()
  await p.locator('.rz-card', { hasText: '@demo.threads' }).waitFor({ timeout: 6000 }).catch(() => {})

  // Konten: generate a post (simulated AI), then upload it to the Threads account from the composer.
  await p.getByRole('radio', { name: 'Konten', exact: true }).click()
  await p.fill('#sm-topic', 'Promo servis AC minggu ini')
  await p.getByRole('button', { name: 'Buat konten' }).click()
  await p.waitForSelector('.workspace-output .sm-composer textarea', { timeout: 20000 })
  const upload = p.locator('.workspace-output').getByRole('button', { name: 'Unggah ke akun terhubung' })
  t.check(await upload.count() === 1, 'Konten offers "Unggah ke akun terhubung"')
  await upload.click()
  await p.waitForSelector('dialog.modal[open] select', { timeout: 6000 })
  const accountSelect = p.locator('dialog.modal select').first()
  const threadsValue = await accountSelect.locator('option', { hasText: 'Threads' }).getAttribute('value')
  await accountSelect.selectOption(threadsValue)
  await p.waitForTimeout(200)
  t.check(await p.locator('dialog.modal select').nth(1).locator('option[value="text"]').count() === 1, 'Threads offers a text post')
  await p.locator('dialog.modal select').nth(1).selectOption('text')
  t.check(await p.locator('dialog.modal textarea[id^="rz-media"]').isHidden(), 'text post: media field hidden')
  const caption = await p.inputValue('dialog.modal textarea')
  if (caption.length > 480) await p.fill('dialog.modal textarea', caption.slice(0, 480))
  await p.getByRole('button', { name: 'Unggah', exact: true }).click()
  await p.waitForSelector('dialog.modal[open]', { state: 'detached', timeout: 6000 }).catch(() => {})
  const left = await p.locator('dialog.modal[open]').count()
  t.check(left === 0, 'post submitted and dialog closed', left ? await p.locator('dialog.modal[open] .field-error').textContent() : '')
  if (left) await p.keyboard.press('Escape')
  await p.getByRole('radio', { name: 'Jadwal', exact: true }).click()
  await p.getByRole('radio', { name: 'Laporan tayang', exact: true }).click()
  await p.waitForSelector('.rz-post', { timeout: 8000 }).catch(() => {})
  t.check(await p.locator('.rz-post', { hasText: 'Threads · @demo.threads' }).count() === 1, 'post listed in Laporan tayang')
  await p.waitForTimeout(2000)
  await p.getByRole('button', { name: 'Muat ulang' }).click()
  await p.locator('.rz-post .status', { hasText: 'Tayang' }).waitFor({ timeout: 8000 }).catch(() => {})
  t.check(await p.locator('.rz-post .status', { hasText: 'Tayang' }).count() === 1, 'status moves to "Tayang" (simulated)')
  t.check(!(await p.evaluate(() => JSON.stringify(localStorage))).includes('secret-abcdef-123'), 'Repliz secret not kept in the browser')

  // Clean up: disconnect the demo accounts so the other social-media spec starts from a clean Akun tab.
  await p.getByRole('radio', { name: 'Akun', exact: true }).click()
  await p.waitForSelector('.rz-account', { timeout: 6000 })
  p.on('dialog', (d) => d.accept())
  for (const name of ['Putuskan Instagram @demo.instagram', 'Putuskan Threads @demo.threads']) {
    await p.getByRole('button', { name }).click()
    await p.waitForTimeout(500)
  }
  t.check(await p.locator('.rz-account').count() === 0, 'accounts disconnected')
  await t.noErrors(p)
}
