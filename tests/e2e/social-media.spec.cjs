// E2E: Media Sosial menu (#/social-media) — Akun + Konten tabs on the mock cloud (demo mode).
const { loginLive, goStage } = require('./lib.cjs')

module.exports = async function socialMedia(t) {
  const p = await t.page()
  await loginLive(p, t.base)
  t.check(await goStage(p, 'social-media'), 'sidebar has "Media Sosial"')
  const tab = (name) => p.getByRole('radio', { name, exact: true })
  await p.waitForSelector('.workspace-tabs .seg-btn')
  const labels = await p.$$eval('.workspace-tabs .seg-btn', (b) => b.map((x) => x.textContent.trim()))
  t.check(labels.join(',') === 'Akun,Konten,Jadwal,Brainstorm,Iklan,Kolaborasi', 'six tabs in order', labels.join(','))

  // OAuth return: query is shown as a message, opens Akun, then stripped
  await p.evaluate(() => { location.hash = '#/social-media?social_error=Izin%20ditolak%20Meta' })
  await p.locator('.note-danger', { hasText: 'Koneksi gagal, coba lagi.' }).waitFor({ timeout: 8000 }).catch(() => {})
  t.check(await p.locator('.note-danger', { hasText: 'Koneksi gagal, coba lagi.' }).count() === 1, 'unknown social_error shown as a generic danger message')
  t.check(await p.locator('.note-danger', { hasText: 'Izin ditolak Meta' }).count() === 0, 'unknown social_error text is not echoed')
  const hash = await p.evaluate(() => location.hash)
  t.check(!hash.includes('social_error'), 'query stripped from hash', hash)
  t.check(await tab('Akun').getAttribute('aria-checked') === 'true', 'Akun tab opened by social_error')

  // legacy import
  await p.evaluate(() => {
    localStorage.setItem('satualur_saved_content', JSON.stringify([{ id: 1, content: 'Ide lama satu', type: 'brainstorm' }, { id: 2, content: 'Caption lama', type: 'caption' }]))
    localStorage.setItem('satualur_schedules', JSON.stringify([{ id: 3, content: 'Jadwal lama' }]))
  })
  await tab('Konten').click()
  await tab('Akun').click()
  await p.getByRole('button', { name: 'Pindahkan ke akun' }).click()
  await p.waitForFunction(() => localStorage.getItem('satualur_social_migrated') === '1', null, { timeout: 8000 }).catch(() => {})
  t.check(await p.evaluate(() => localStorage.getItem('satualur_social_migrated')) === '1', 'import sets migrated flag')
  t.check(await p.evaluate(() => Boolean(localStorage.getItem('satualur_saved_content'))), 'import keeps old keys')

  // not connected: Konten points to Akun
  await tab('Konten').click()
  await p.waitForSelector('.workspace-library .sm-composer')
  t.check(await p.getByRole('button', { name: 'Hubungkan akun di tab Akun untuk membagikan.' }).count() >= 1, 'not connected: link to the Akun tab instead of checkboxes')
  t.check(await p.locator('.workspace-library input[value=facebook]').count() === 0, 'not connected: no platform checkboxes')
  await tab('Akun').click()

  // Page picker (demo lists a Page for any pick id); choosing it connects
  await p.evaluate(() => { location.hash = '#/social-media?social_pick=abc' })
  await p.getByRole('button', { name: 'Pilih Demo Page' }).click()
  await p.waitForSelector('text=Demo Page', { timeout: 8000 })
  t.check(await p.getByRole('button', { name: 'Putuskan' }).count() === 1, 'picking a Page connects the account')

  // connected message from the OAuth return
  await p.evaluate(() => { location.hash = '#/social-media?social=connected' })
  await p.locator('.note-ok', { hasText: 'Akun berhasil terhubung.' }).waitFor({ timeout: 8000 }).catch(() => {})
  t.check(await p.locator('.note-ok', { hasText: 'Akun berhasil terhubung.' }).count() === 1, 'social=connected shows success message')

  // disconnect (confirm) then connect again
  p.once('dialog', (d) => d.accept())
  await p.getByRole('button', { name: 'Putuskan' }).click()
  await p.getByRole('button', { name: 'Hubungkan Facebook & Instagram' }).waitFor({ timeout: 8000 }).catch(() => {})
  t.check(await p.getByRole('button', { name: 'Hubungkan Facebook & Instagram' }).count() === 1, 'Putuskan (confirmed) returns to the not-connected state')
  await p.getByRole('button', { name: 'Hubungkan Facebook & Instagram' }).click()
  await p.waitForSelector('text=Demo Page', { timeout: 8000 })
  t.check(await p.getByText('Demo Page').count() >= 1, 'Akun shows "Demo Page" after connecting')

  // Konten: generate, save, share
  await tab('Konten').click()
  await p.waitForSelector('#sm-topic')
  const opts = (await p.locator('#sm-platform option').allTextContents()).join(',')
  t.check(opts === 'Instagram,Facebook,Threads', 'platform choices are Instagram, Facebook, Threads', opts)
  await p.fill('#sm-topic', 'Perawatan AC rumah')
  await p.getByRole('button', { name: 'Buat konten' }).click()
  await p.waitForSelector('.workspace-output .sm-composer', { timeout: 25000 })
  const out = p.locator('.workspace-output .sm-composer')
  await out.getByRole('button', { name: 'Simpan', exact: true }).click()
  await p.waitForSelector('.workspace-library .sm-composer', { timeout: 8000 })
  t.check(await p.locator('.workspace-library .sm-composer').count() >= 1, 'saved content appears in the library')
  const item = p.locator('.workspace-library .sm-composer').first()
  await item.getByLabel('Isi konten').fill('Tips E2E: bersihkan filter AC.')
  await item.getByRole('button', { name: 'Simpan', exact: true }).click()
  const ig = item.locator('input[value=instagram]')
  t.check(await ig.isDisabled(), 'Instagram checkbox disabled without image')
  t.check(await item.getByText('Instagram wajib memakai gambar.').count() >= 1, 'Instagram reason shown as hint')
  await item.locator('input[value=facebook]').check()
  await item.getByRole('button', { name: 'Bagikan sekarang' }).click()
  await p.locator('.toast', { hasText: 'Tayang di Facebook' }).first().waitFor({ timeout: 10000 }).catch(() => {})
  t.check(await p.locator('.toast', { hasText: 'Tayang di Facebook' }).count() >= 1, 'toast "Tayang di Facebook"')

  // share without platform
  await item.locator('input[value=facebook]').uncheck()
  await item.getByRole('button', { name: 'Bagikan sekarang' }).click()
  t.check(await p.locator('.note-danger', { hasText: 'Pilih minimal satu platform' }).count() === 1, 'share without platform is refused')

  // image makes Instagram eligible
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==', 'base64')
  await item.getByLabel('Gambar (opsional)').setInputFiles({ name: 'a.png', mimeType: 'image/png', buffer: png })
  await p.waitForFunction(() => !document.querySelector('.workspace-library .sm-composer input[value=instagram]')?.disabled, null, { timeout: 8000 }).catch(() => {})
  t.check(await ig.isEnabled(), 'Instagram checkbox enabled after adding a 1:1 image')

  // caption with more than 30 hashtags disables Instagram again
  await item.getByLabel('Isi konten').fill(Array.from({ length: 31 }, (_, i) => `#tag${i}`).join(' '))
  t.check(await ig.isDisabled(), 'Instagram disabled when the caption has more than 30 hashtags')
  t.check(await item.getByText('Instagram maksimal 30 hashtag.').count() >= 1, 'hashtag reason shown as hint')

  // Jadwal: schedule, report, cancel, failed share
  await tab('Jadwal').click()
  await p.waitForSelector('.sm-schedule-item')
  const first = p.locator('.sm-schedule-item').first()
  const open = first.getByRole('button', { name: 'Jadwalkan tayang' })
  await open.click()
  const dlg = p.getByRole('dialog', { name: 'Jadwalkan tayang' })
  await dlg.waitFor()
  await dlg.getByRole('button', { name: 'Simpan jadwal' }).click()
  t.check(await dlg.getByText('Pilih tanggal dan waktu.').count() === 1, 'empty time keeps the dialog open with a message')
  const soon = await p.evaluate(() => { const d = new Date(Date.now() + 2 * 60000 - new Date().getTimezoneOffset() * 60000); return d.toISOString().slice(0, 16) })
  await dlg.getByLabel('Tanggal dan waktu').fill(soon)
  await dlg.locator('input[value=facebook]').check()
  await dlg.getByRole('button', { name: 'Simpan jadwal' }).click()
  await dlg.waitFor({ state: 'hidden' })
  t.check(await open.evaluate((b) => b === document.activeElement), 'focus returns to the opener')
  await p.getByRole('radio', { name: 'Laporan tayang', exact: true }).click()
  await p.locator('.sm-report-row', { hasText: 'Terjadwal' }).first().waitFor({ timeout: 8000 })
  t.check(await p.locator('.sm-report-row', { hasText: 'Terjadwal' }).count() >= 1, 'Laporan shows "Terjadwal"')
  await p.locator('.sm-report-row', { hasText: 'Terjadwal' }).first().getByRole('button', { name: 'Batalkan' }).click()
  await p.locator('.sm-report-row', { hasText: 'Dibatalkan' }).first().waitFor({ timeout: 8000 })
  t.check(await p.locator('.sm-report-row', { hasText: 'Dibatalkan' }).count() >= 1, 'Batalkan -> "Dibatalkan"')

  await tab('Konten').click()
  await p.waitForSelector('.workspace-library .sm-composer')
  const bad = p.locator('.workspace-library .sm-composer').first()
  await bad.getByLabel('Isi konten').fill('Tes #gagal')
  await bad.locator('input[value=facebook]').check()
  await bad.getByRole('button', { name: 'Bagikan sekarang' }).click()
  await p.locator('.toast', { hasText: 'Meta menolak posting' }).first().waitFor({ timeout: 10000 }).catch(() => {})
  await tab('Jadwal').click()
  await p.getByRole('radio', { name: 'Laporan tayang', exact: true }).click()
  await p.locator('.sm-report-row', { hasText: 'Gagal' }).first().waitFor({ timeout: 8000 })
  t.check(await p.locator('.sm-report-row', { hasText: 'Meta menolak posting (simulasi).' }).count() >= 1, 'Laporan shows Gagal with the error text')
  await p.getByRole('button', { name: 'Muat ulang' }).click()

  // Threads: connect in demo, text-only share, report link, #gagal, Threads-only business, independent disconnects
  const threadsCard = () => p.locator('section.panel', { has: p.getByRole('heading', { name: 'Akun Threads' }) })
  const fbCard = () => p.locator('section.panel', { has: p.getByRole('heading', { name: 'Akun Meta' }) })
  await tab('Akun').click()
  await threadsCard().getByRole('button', { name: 'Hubungkan Threads' }).click()
  await threadsCard().getByText('@demo.threads').waitFor({ timeout: 8000 }).catch(() => {})
  t.check(await threadsCard().getByText('@demo.threads').count() === 1, 'Threads card shows @demo.threads after connecting')
  t.check(await fbCard().getByText('Demo Page').count() === 1, 'connecting Threads keeps Facebook connected')
  await p.evaluate(() => { location.hash = '#/social-media?social=threads_connected' })
  await p.locator('.note-ok', { hasText: 'Akun Threads berhasil terhubung.' }).waitFor({ timeout: 8000 }).catch(() => {})
  t.check(await p.locator('.note-ok', { hasText: 'Akun Threads berhasil terhubung.' }).count() === 1, 'social=threads_connected shows its success message')

  await tab('Konten').click()
  await p.waitForSelector('.workspace-library .sm-composer')
  const thItem = p.locator('.workspace-library .sm-composer').first()
  await thItem.getByLabel('Isi konten').fill('Tips Threads: cek freon AC setahun sekali.')
  const thBox = thItem.locator('input[value=threads]')
  t.check(await thBox.isEnabled(), 'Threads checkbox enabled for short text')
  await thItem.getByLabel('Isi konten').fill('Dua tag #ac #servis')
  t.check(await thBox.isDisabled() && await thItem.getByText('Threads maksimal 1 tag topik.').count() >= 1, 'two tags disable Threads with the reason as hint')
  await thItem.getByLabel('Isi konten').fill('Tips Threads: cek freon AC setahun sekali.')
  if (await thItem.getByRole('button', { name: 'Hapus gambar' }).count()) await thItem.getByRole('button', { name: 'Hapus gambar' }).click()
  await thBox.check()
  await thItem.getByRole('button', { name: 'Bagikan sekarang' }).click()
  await p.locator('.toast', { hasText: 'Tayang di Threads' }).first().waitFor({ timeout: 10000 }).catch(() => {})
  t.check(await p.locator('.toast', { hasText: 'Tayang di Threads' }).count() >= 1, 'text-only share to Threads: toast "Tayang di Threads"')
  await thItem.getByLabel('Isi konten').fill('Threads #gagal')
  await thBox.check()
  await thItem.getByRole('button', { name: 'Bagikan sekarang' }).click()
  await p.locator('.toast', { hasText: 'Meta menolak posting' }).first().waitFor({ timeout: 10000 }).catch(() => {})
  await tab('Jadwal').click()
  await p.getByRole('radio', { name: 'Laporan tayang', exact: true }).click()
  const thPosted = p.locator('.sm-report-row', { hasText: 'Threads' }).filter({ hasText: 'Tayang' }).first()
  await thPosted.waitFor({ timeout: 8000 }).catch(() => {})
  t.check(/^https:\/\/www\.threads\.net\/@demo\.threads\/post\/demo\d+$/.test(await thPosted.getByRole('link', { name: /Lihat posting/ }).getAttribute('href').catch(() => '')),
    'Laporan shows the Threads post as Tayang with its link')
  t.check(await p.locator('.sm-report-row', { hasText: 'Threads' }).filter({ hasText: 'Gagal' }).count() >= 1, '#gagal fails the Threads post')

  // Threads-only business: disconnect Facebook
  await tab('Akun').click()
  p.once('dialog', (d) => d.accept())
  await fbCard().getByRole('button', { name: 'Putuskan' }).click()
  await fbCard().getByRole('button', { name: 'Hubungkan Facebook & Instagram' }).waitFor({ timeout: 8000 }).catch(() => {})
  t.check(await threadsCard().getByText('@demo.threads').count() === 1, 'disconnecting Facebook keeps Threads connected')
  await tab('Konten').click()
  await p.waitForSelector('.workspace-library .sm-composer')
  const only = p.locator('.workspace-library .sm-composer').first()
  t.check(await only.locator('input[value=facebook], input[value=instagram]').count() === 0 && await only.locator('input[value=threads]').count() === 1,
    'Threads-only business sees only the Threads checkbox')
  await tab('Jadwal').click()
  await p.getByRole('radio', { name: 'Daftar konten', exact: true }).click()
  await p.locator('.sm-schedule-item').first().getByRole('button', { name: 'Jadwalkan tayang' }).click()
  const thDlg = p.getByRole('dialog', { name: 'Jadwalkan tayang' })
  await thDlg.waitFor()
  t.check(await thDlg.locator('input[value=facebook]').count() === 0 && await thDlg.locator('input[value=threads]').count() === 1, 'Jadwal dialog offers only Threads')
  await thDlg.getByRole('button', { name: 'Batal' }).click()

  // Reconnect Facebook, then disconnecting Threads leaves Facebook connected
  await tab('Akun').click()
  await fbCard().getByRole('button', { name: 'Hubungkan Facebook & Instagram' }).click()
  await fbCard().getByText('Demo Page').waitFor({ timeout: 8000 })
  p.once('dialog', (d) => d.accept())
  await threadsCard().getByRole('button', { name: 'Putuskan' }).click()
  await threadsCard().getByRole('button', { name: 'Hubungkan Threads' }).waitFor({ timeout: 8000 }).catch(() => {})
  t.check(await threadsCard().getByRole('button', { name: 'Hubungkan Threads' }).count() === 1 && await fbCard().getByText('Demo Page').count() === 1,
    'disconnecting Threads leaves Facebook connected')

  // Brainstorm reuses the generator and saves automatically
  await tab('Brainstorm').click()
  await p.fill('#sm-topic', 'Musim hujan')
  await p.getByRole('button', { name: 'Mulai brainstorm' }).click()
  await p.waitForSelector('.workspace-library .workspace-entry', { timeout: 25000 })
  t.check(await p.locator('.workspace-library .workspace-entry').count() >= 1, 'brainstorm result saved to the library')
  await t.noErrors(p)

  // Kolaborasi: influencer cards + request dialog
  await tab('Kolaborasi').click()
  await p.waitForSelector('.sm-inf-card')
  t.check(await p.locator('.sm-inf-card').count() === 6, 'Kolaborasi shows 6 influencer cards')
  const kolab = await p.locator('.workspace-stack').first().textContent()
  t.check(!kolab.includes('mailto:') && !(await p.locator('a[href^="mailto:"]').count()) && !/Rp\d/.test(kolab), 'Kolaborasi has no mailto or old prices')
  await p.locator('.sm-inf-card').first().getByRole('button', { name: 'Ajukan kolaborasi' }).click()
  const cd = p.getByRole('dialog', { name: /Aulia Rahma/ })
  await cd.getByRole('button', { name: 'Kirim permintaan' }).click()
  t.check(await cd.locator('.field-error').first().textContent() === 'Ceritakan kampanye Anda.', 'collab dialog shows the validator message')
  await cd.getByLabel('Ceritakan kampanye Anda').fill('Promosi kedai baru')
  await cd.getByLabel('Kisaran anggaran').fill('Rp2-5 juta')
  await cd.getByLabel('Waktu kampanye').fill('Desember 2026')
  await cd.getByRole('button', { name: 'Kirim permintaan' }).click()
  await cd.waitFor({ state: 'hidden' })
  await p.locator('.sm-request', { hasText: 'Baru' }).first().waitFor({ timeout: 8000 })
  t.check(await p.locator('.sm-request', { hasText: 'Aulia Rahma' }).count() === 1, 'Permintaan saya (collab) lists the request as Baru')

  // Iklan: request form
  await tab('Iklan').click()
  t.check(await p.locator('.sm-request').count() === 0, 'Iklan lists only ads requests')
  await p.getByRole('button', { name: 'Ajukan iklan' }).click()
  t.check(await p.locator('#ads-req-err').textContent() === 'Layanan yang diiklankan wajib diisi.', 'empty Layanan shows the validator message')
  t.check(await p.locator('.sm-request').count() === 0, 'nothing sent on invalid ads form')
  await p.fill('#ads-req-service', 'Servis AC')
  await p.fill('#ads-req-budget', '50000')
  await p.getByRole('button', { name: 'Ajukan iklan' }).click()
  await p.locator('.sm-request', { hasText: 'Baru' }).first().waitFor({ timeout: 8000 })
  t.check(await p.locator('.sm-request').count() === 1, 'Permintaan saya (ads) lists the request as Baru')

  // WIB device: a picked local time is stored as its UTC instant and shown back as the same local time
  const q = await t.page({ timezoneId: 'Asia/Jakarta' })
  await loginLive(q, t.base)
  await goStage(q, 'social-media')
  await q.getByRole('button', { name: 'Hubungkan Facebook & Instagram' }).click()
  await q.waitForSelector('text=Demo Page', { timeout: 8000 })
  await q.getByRole('radio', { name: 'Konten', exact: true }).click()
  await q.fill('#sm-topic', 'Zona waktu')
  await q.getByRole('button', { name: 'Buat konten' }).click()
  await q.waitForSelector('.workspace-output .sm-composer', { timeout: 25000 })
  await q.locator('.workspace-output .sm-composer').getByRole('button', { name: 'Simpan', exact: true }).click()
  await q.waitForSelector('.workspace-library .sm-composer', { timeout: 8000 })
  await q.getByRole('radio', { name: 'Jadwal', exact: true }).click()
  await q.locator('.sm-schedule-item').first().getByRole('button', { name: 'Jadwalkan tayang' }).click()
  const wib = q.getByRole('dialog', { name: 'Jadwalkan tayang' })
  const ymd = new Date(Date.now() + 24 * 3600e3).toISOString().slice(0, 10)
  await wib.getByLabel('Tanggal dan waktu').fill(`${ymd}T10:00`)
  await wib.locator('input[value=facebook]').check()
  await wib.getByRole('button', { name: 'Simpan jadwal' }).click()
  await wib.waitFor({ state: 'hidden' })
  await q.getByRole('radio', { name: 'Laporan tayang', exact: true }).click()
  const row = q.locator('.sm-report-row', { hasText: 'Terjadwal' }).first()
  await row.waitFor({ timeout: 8000 })
  t.check(/10[.:]00/.test(await row.textContent()), 'Laporan shows the picked WIB time', await row.textContent())
  const stored = await q.evaluate(() => JSON.parse(localStorage.getItem('satualur_social_demo_v1')).posts.map((r) => r.scheduled_at))
  t.check(stored.includes(`${ymd}T03:00:00.000Z`), 'scheduled_at stored as the UTC instant (WIB - 7h)', stored.join(','))
}
